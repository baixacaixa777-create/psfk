create table if not exists public.campanhas (
  token text primary key,
  titulo text default '',
  empresa text default '',
  dev_id text default '',
  nota text default '',
  num_avaliacoes text default '',
  classificacao text default '',
  downloads text default '',
  descricao text default '',
  descricao_curta text default '',
  atualizado_em text default '',
  disponivel_em text default '',
  icone_url text default '',
  screenshots jsonb default '[]'::jsonb,
  comentarios jsonb default '[]'::jsonb,
  exibir jsonb default '{}'::jsonb,
  apk_url text default '',
  criado_em timestamptz default now()
);

alter table public.campanhas enable row level security;

-- Parte 2: contas, assinaturas, 2FA (TOTP) e sessões
create table if not exists public.usuarios (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  nome text not null default '',
  senha_hash text not null,
  admin boolean not null default false,
  plano text not null default 'mensal',
  assinatura_status text not null default 'pendente',
  assinatura_vence_em timestamptz,
  twofa_secret text,
  twofa_ativo boolean not null default false,
  criado_em timestamptz default now()
);
alter table public.usuarios enable row level security;

create table if not exists public.sessoes (
  token text primary key,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  pendente boolean not null default false,
  criado_em timestamptz default now(),
  expira_em timestamptz not null
);
alter table public.sessoes enable row level security;

alter table public.campanhas add column if not exists usuario_id uuid;
alter table public.campanhas add column if not exists expira_em timestamptz;
alter table public.campanhas add column if not exists aviso_3d boolean not null default false;
create index if not exists campanhas_usuario_idx on public.campanhas (usuario_id);

-- registro de acessos das páginas públicas (painel do admin)
create table if not exists public.acessos (
  id bigint generated by default as identity primary key,
  token text not null,
  user_agent text not null default '',
  criado_em timestamptz default now()
);
create index if not exists acessos_token_idx on public.acessos (token, criado_em);

